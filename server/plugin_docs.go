func writeCapabilitiesSection(b *strings.Builder) {
	b.WriteString("## What a plugin can reach\n\n")
	b.WriteString("Nothing here is gated. A plugin does what it does, and the decision about\n")
	b.WriteString("whether to trust it happens once, at install.\n\n")

	for _, capability := range pluginCapabilities {
		if len(capability.methods) == 0 {
			continue
		}

		b.WriteString("### `rdio." + capability.name + "`\n\n")
		b.WriteString(capability.summary + "\n\n")

		for _, method := range capability.methods {
			b.WriteString("- `" + method + "`\n")
		}
		b.WriteString("\n")
	}
}

func writeVerbsSection(b *strings.Builder) {
	b.WriteString("## The four verbs\n\n")
	b.WriteString("Everything a plugin does to the server is one of these, registered against a\n")
	b.WriteString("named extension point.\n\n")
	b.WriteString("| Verb | Meaning |\n|---|---|\n")
	b.WriteString("| `rdio.on(point, fn)` | Observe. Runs asynchronously and cannot change anything. |\n")
	b.WriteString("| `rdio.filter(point, fn)` | Modify what passes through, or veto it by returning `{drop: true}`. |\n")
	b.WriteString("| `rdio.override(point, fn)` | Replace the server's behaviour for that point entirely. |\n")
	b.WriteString("| `rdio.provide(point, fn)` | Supply something the server does not have. First answer wins. |\n\n")

	b.WriteString("`rdio.definePoint(name)` publishes a point of your own, so other plugins can\n")
	b.WriteString("extend yours.\n\n")

	b.WriteString("Registering against a point that does not exist is an error, rather than a\n")
	b.WriteString("handler that silently never runs.\n\n")

	b.WriteString("A `filter` or `provide` handler that times out, throws, or returns something\n")
	b.WriteString("unusable is treated as having done nothing, and whatever it was given passes\n")
	b.WriteString("through unchanged. `override` is the exception: replacing behaviour means\n")
	b.WriteString("owning its failures, because there is no original left to fall back to.\n\n")
}

func writePointsSection(b *strings.Builder) {
	b.WriteString("## Extension points\n\n")

	groups := []struct {
		title  string
		points []string
	}{
		{"Lifecycle", []string{
			PointStartup, PointShutdown, PointTick, PointConfigChanged,
			PointClientConnect, PointClientDisconnect,
		}},
		{"Ingest", []string{
			PointCallReceive, PointCallAccept, PointCallDuplicate,
			PointCallConvert, PointCallStore, PointCallStored,
		}},
		{"Delivery", []string{
			PointCallDelay, PointCallEmit, PointCallPayload, PointCallEmitted,
			PointDownstreamSend, PointClientConfig,
		}},
		{"Access", []string{
			PointAccessCheck, PointAccessScope, PointApikeyCheck, PointAdminCheck,
		}},
		{"Data", []string{
			PointCallSearch, PointCallPrune, PointCallAudio, PointConfigSave,
		}},
	}

	for _, group := range groups {
		b.WriteString("### " + group.title + "\n\n")
		b.WriteString("| Point | Timeout | Notes |\n|---|---|---|\n")

		for _, point := range group.points {
			timeout := "default"
			if custom, ok := pointTimeouts[point]; ok {
				timeout = custom.String()
			}

			note := pointNotes[point]
			b.WriteString(fmt.Sprintf("| `%s` | %s | %s |\n", point, timeout, note))
		}

		b.WriteString("\n")
	}
}

func writeModelsSection(b *strings.Builder) {
	b.WriteString("## Configuration models\n\n")
	b.WriteString("`rdio.models.<name>` reads and writes the server's configuration. Each one\n")
	b.WriteString("offers `list()`, `get(id)`, `set(entry)` and `remove(id)`. Entries are the same\n")
	b.WriteString("shape the admin panel uses.\n\n")

	for i := range pluginModels {
		model := &pluginModels[i]

		b.WriteString("### `rdio.models." + model.name + "`\n\n")
		b.WriteString(model.summary + "\n\n")

		fields := modelFields(model.sample)
		if len(fields) == 0 {
			continue
		}

		b.WriteString("Fields: ")
		for j, field := range fields {
			if j > 0 {
				b.WriteString(", ")
			}
			b.WriteString("`" + field + "`")
		}
		b.WriteString("\n\nIdentified by `" + model.key + "`.\n\n")
	}
}

