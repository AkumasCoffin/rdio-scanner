// The plugin API reference, written by the server itself.
//
// A review of the hand-written documentation found six capabilities that worked
// but were documented nowhere, three that existed but were never mentioned, and
// one documented in detail that did nothing at all. That is what two parallel
// lists maintained by hand always become.
//
// So the reference is emitted from the same declarations the code runs on: the
// point catalogue in plugin_points.go and the model catalogue in
// plugin_models.go. Adding a point or a model documents it. Removing one
// removes its documentation. The two cannot disagree, because there is only one
// of them.
//
// Run with -plugin_docs <file> to write it.

func writePluginDocs(path string) error {
	var b strings.Builder

	b.WriteString("# Plugin API reference\n\n")
	b.WriteString(fmt.Sprintf(
		"Generated by Rdio Scanner %s. Do not edit — run `rdio-scanner -plugin_docs` to regenerate.\n\n",
		Version,
	))
	b.WriteString(fmt.Sprintf("Plugin API version: **%d**\n\n", CurrentPluginApiVersion))
	b.WriteString("A plugin declares `\"apiVersion\": " + fmt.Sprint(CurrentPluginApiVersion) +
		"` in its manifest. The server refuses a plugin written for a newer API than it\n" +
		"knows, and supports one version back — so a plugin keeps working across server\n" +
		"updates without being rebuilt.\n\n")

	writeVerbsSection(&b)
	writeCapabilitiesSection(&b)
	writePointsSection(&b)
	writeModelsSection(&b)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// pluginCapabilities describes each top-level rdio.* namespace.
//
// Unlike points and models these cannot be derived — a Go closure bound into a
// runtime does not carry its JavaScript signature — so this is written by hand.
// What stops it drifting is TestEveryCapabilityIsDocumented, which reads the
// bindings out of plugin_api.go and fails if one is missing here. That is the
// check that would have caught the six capabilities the review found working
// but documented nowhere.
